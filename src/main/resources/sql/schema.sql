-- FYNXT Java Developer Assignment
-- Minimal normalized schema for the Order Booking & Portfolio API.
-- Dialect: PostgreSQL
--
-- Tables:
--   1. traders            - trader identities
--   2. stocks             - stock master data (symbol, name, sector)
--   3. trade_orders       - BUY/SELL order history and state
--   4. portfolio_holdings - current stock positions per trader
--
-- Concurrency note:
-- The "maximum 3 PENDING orders per trader" rule cannot be safely enforced
-- by a simple CHECK constraint. In Java, place-order logic should run in a
-- transaction and lock the corresponding traders row (SELECT ... FOR UPDATE)
-- before counting pending orders and inserting a new order.
--
-- Sector overlap baskets are fixed business constants in Java, as required
-- by the assignment. They do not need database tables.

CREATE TABLE traders (
    trader_id       VARCHAR(50) PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_trader_id_not_blank CHECK (LENGTH(TRIM(trader_id)) > 0)
);

CREATE TABLE stocks (
    stock_symbol    VARCHAR(10) PRIMARY KEY,
    stock_name      VARCHAR(100) NOT NULL,
    sector          VARCHAR(50) NOT NULL,

    CONSTRAINT ck_stock_symbol_not_blank CHECK (LENGTH(TRIM(stock_symbol)) > 0),
    CONSTRAINT ck_stock_name_not_blank CHECK (LENGTH(TRIM(stock_name)) > 0),
    CONSTRAINT ck_stock_sector_not_blank CHECK (LENGTH(TRIM(sector)) > 0)
);

CREATE TABLE trade_orders (
    order_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trader_id       VARCHAR(50) NOT NULL,
    stock_symbol    VARCHAR(10) NOT NULL,
    quantity        BIGINT NOT NULL,
    side            VARCHAR(4) NOT NULL,
    status          VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_trader FOREIGN KEY (trader_id) REFERENCES traders (trader_id),
    CONSTRAINT fk_order_stock FOREIGN KEY (stock_symbol) REFERENCES stocks (stock_symbol),
    CONSTRAINT ck_order_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_order_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT ck_order_status  CHECK (status IN ('PENDING', 'FILLED', 'CANCELLED'))
);

CREATE TABLE portfolio_holdings (
    holding_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trader_id       VARCHAR(50) NOT NULL,
    stock_symbol    VARCHAR(10) NOT NULL,
    quantity        BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_holding_trader FOREIGN KEY (trader_id) REFERENCES traders (trader_id),
    CONSTRAINT fk_holding_stock FOREIGN KEY (stock_symbol) REFERENCES stocks (stock_symbol),
    CONSTRAINT uq_holding_trader_stock UNIQUE (trader_id, stock_symbol),
    CONSTRAINT ck_holding_quantity_nonnegative CHECK (quantity >= 0)
);

-- Supports counting pending orders for the per-trader limit and order lookup.
CREATE INDEX idx_trade_orders_trader_status ON trade_orders (trader_id, status);

-- Supports trader order history.
CREATE INDEX idx_trade_orders_trader_created ON trade_orders (trader_id, created_at DESC);

-- Supports portfolio lookup by trader.
CREATE INDEX idx_portfolio_holdings_trader ON portfolio_holdings (trader_id);

