-- Notes for Java service implementation:
-- 1. Create a traders row when a trader is first registered/onboarded.
-- 2. Validate requested stock_symbol against stocks; derive sector from this
--    table rather than trusting a sector value supplied by the API client.
-- 3. Place order: lock the traders row, count PENDING orders, enforce max 3,
--    and for SELL validate available holding in the same transaction.
-- 4. Fill BUY/SELL and update the holding in the same transaction as the
--    order status transition. Never allow a holding to become negative.
-- 5. Fill/cancel: atomically transition only PENDING orders; reject any
--    transition from FILLED/CANCELLED. Lock the order row or use optimistic
--    locking to prevent concurrent fill/cancel races.
-- 6. For Add to Portfolio, validate the stock exists and atomically add to
--    the trader's existing holding (or insert a new holding row).
-- 7. Portfolio sector breakdown can join portfolio_holdings to stocks and
--    aggregate quantities by stocks.sector.
-- 8. Keep TECH_HEAVY, FINANCE_HEAVY, BALANCED basket definitions and overlap/
--    risk calculations in pure Java, with no DB calls in the overlap logic.
